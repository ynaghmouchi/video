#!/usr/bin/env python3
"""Generate the French voice-over + exact word timings for the BeerFlood short.

Needs internet access (edge-tts talks to speech.platform.bing.com):
    pip install edge-tts
    python3 scripts/tts-edge.py

Writes:
  public/beerflood/voice.mp3        narration (one clip per line, concatenated with silences)
  src/beerflood/vo.gen.ts           WORDS with exact start/end from edge-tts WordBoundary events
"""
import asyncio, json, os, re, subprocess, sys, tempfile

import edge_tts

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VOICE = os.environ.get("EDGE_VOICE", "fr-FR-HenriNeural")
RATE = os.environ.get("EDGE_RATE", "+8%")

def read_lines():
    src = open(os.path.join(ROOT, "src/beerflood/script.ts"), encoding="utf8").read()
    pat = re.compile(r'id:\s*"([^"]+)",\s*text:\s*"([^"]+)",\s*start:\s*([\d.]+),\s*end:\s*([\d.]+)')
    return [(m.group(1), m.group(2), float(m.group(3)), float(m.group(4))) for m in pat.finditer(src)]

async def synth(text, path):
    tts = edge_tts.Communicate(text, VOICE, rate=RATE)
    words = []
    with open(path, "wb") as f:
        async for chunk in tts.stream():
            if chunk["type"] == "audio":
                f.write(chunk["data"])
            elif chunk["type"] == "WordBoundary":
                words.append((chunk["text"], chunk["offset"] / 1e7, (chunk["offset"] + chunk["duration"]) / 1e7))
    return words

def duration(path):
    out = subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path])
    return float(out)

async def main():
    lines = read_lines()
    tmp = tempfile.mkdtemp()
    all_words, segments, cursor = [], [], 0.0
    for lid, text, start, end in lines:
        clip = os.path.join(tmp, f"{lid}.mp3")
        words = await synth(text, clip)
        gap = max(0.0, start - cursor)
        if gap > 0:
            segments.append(("silence", gap))
        segments.append(("file", clip))
        for w, s, e in words:
            all_words.append({"text": w, "start": round(start + s, 3), "end": round(start + e, 3), "line": lid})
        cursor = start + duration(clip)
        print(f"{lid}: {cursor:.2f}s (line window ends {end:.2f}s)", file=sys.stderr)
    # Build ffmpeg concat with silences.
    inputs, filters, idx = [], [], 0
    for kind, v in segments:
        if kind == "silence":
            inputs += ["-f", "lavfi", "-t", f"{v:.3f}", "-i", "anullsrc=r=24000:cl=mono"]
        else:
            inputs += ["-i", v]
        filters.append(f"[{idx}:a]aformat=sample_rates=24000:channel_layouts=mono[a{idx}]")
        idx += 1
    concat = "".join(f"[a{i}]" for i in range(idx)) + f"concat=n={idx}:v=0:a=1[out]"
    out_dir = os.path.join(ROOT, "public/beerflood"); os.makedirs(out_dir, exist_ok=True)
    out_mp3 = os.path.join(out_dir, "voice.mp3")
    subprocess.check_call(["ffmpeg", "-y", "-v", "error", *inputs, "-filter_complex", ";".join(filters) + ";" + concat, "-map", "[out]", "-b:a", "128k", out_mp3])
    ts = "// AUTO-GENERATED by scripts/tts-edge.py — do not hand-edit.\n"
    ts += "export type Word = { text: string; start: number; end: number; line: string };\n"
    ts += 'export const VO_SOURCE: "estimated" | "edge-tts" = "edge-tts";\n'
    ts += "export const WORDS: Word[] = " + json.dumps(all_words, ensure_ascii=False, indent=2) + ";\n"
    open(os.path.join(ROOT, "src/beerflood/vo.gen.ts"), "w", encoding="utf8").write(ts)
    print(f"wrote {out_mp3} and src/beerflood/vo.gen.ts ({len(all_words)} words)", file=sys.stderr)

asyncio.run(main())
